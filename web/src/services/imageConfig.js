/**
 * Resolves local image URLs and provides high-quality defaults based on search criteria.
 */
export function resolveProductImage(productName = '', category = '', src = '') {
  if (src && src.startsWith('http')) return src;

  const cat = String(category || '').toLowerCase();
  const name = String(productName || '').toLowerCase();

  // 1. Sarees varieties
  if (name.includes('banarasi') && name.includes('saree')) return IMAGES.products.banarasiSaree;
  if (name.includes('kanchipuram') && name.includes('saree')) return IMAGES.products.kanchipuramSaree;
  if (name.includes('cotton') && name.includes('saree')) return IMAGES.products.cottonSaree;
  if (name.includes('linen') && name.includes('saree')) return IMAGES.products.linenSaree;
  if (name.includes('organza') && name.includes('saree')) return IMAGES.products.organzaSaree;
  if (name.includes('chiffon') && name.includes('saree')) return IMAGES.products.chiffonSaree;
  if (name.includes('party') && name.includes('saree')) return IMAGES.products.partySaree;
  if (name.includes('bridal') && name.includes('saree')) return IMAGES.products.bridalSaree;

  // 2. Blouses varieties
  if (name.includes('bridal') && name.includes('blouse')) return IMAGES.products.bridalBlouse;
  if (name.includes('designer') && name.includes('blouse')) return IMAGES.products.designerBlouse;
  if (name.includes('boat neck')) return IMAGES.products.boatNeck;
  if (name.includes('princess cut')) return IMAGES.products.princessCut;
  if (name.includes('high neck')) return IMAGES.products.highNeck;
  if (name.includes('puff sleeve')) return IMAGES.products.puffSleeve;
  if (name.includes('embroidered') && name.includes('blouse')) return IMAGES.products.embroideredBlouse;
  if (name.includes('maggam') && name.includes('blouse')) return IMAGES.products.maggamBlouse;

  // 3. Lehengas varieties
  if (name.includes('bridal') && name.includes('lehenga')) return IMAGES.products.bridalLehenga;
  if (name.includes('reception') && name.includes('lehenga')) return IMAGES.products.receptionLehenga;
  if (name.includes('party') && name.includes('lehenga')) return IMAGES.products.partyLehenga;
  if (name.includes('designer') && name.includes('lehenga')) return IMAGES.products.designerLehenga;

  // 4. Kurtis varieties
  if (name.includes('cotton') && name.includes('kurti')) return IMAGES.products.cottonKurti;
  if (name.includes('office') && name.includes('kurti')) return IMAGES.products.officeKurti;
  if (name.includes('printed') && name.includes('kurti')) return IMAGES.products.printedKurti;
  if (name.includes('designer') && name.includes('kurti')) return IMAGES.products.designerKurti;

  // 5. Men's wear
  if (name.includes('sherwani')) return IMAGES.products.sherwani;
  if (name.includes('kurta') && (name.includes('men') || cat.includes('men'))) return IMAGES.products.kurta;
  if (name.includes('nehru') && name.includes('jacket')) return IMAGES.products.nehruJacket;
  if (name.includes('waistcoat')) return IMAGES.products.waistcoat;

  // 6. Generic Category Fallbacks
  if (cat.includes('saree') || name.includes('saree')) return IMAGES.categories.saree;
  if (cat.includes('lehenga') || name.includes('lehenga')) return IMAGES.categories.lehenga;
  if (cat.includes('blouse') || name.includes('blouse')) return IMAGES.categories.blouse;
  if (cat.includes('kurti') || cat.includes('kurta') || name.includes('kurta') || name.includes('kurti')) return IMAGES.categories.kurti;
  if (cat.includes('men') || name.includes('men') || name.includes('kurta')) return IMAGES.categories.mensWear;
  if (cat.includes('gown') || name.includes('gown')) return IMAGES.categories.gowns;

  return IMAGES.placeholder;
}

